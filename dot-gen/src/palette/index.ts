export const DEFAULT_PALETTE: string[] = ['#000000', '#ffffff'];

export function pickByIndex(palette: string[], i: number): string {
  if (palette.length === 0) return '#000000';
  const idx = ((i % palette.length) + palette.length) % palette.length;
  return palette[idx];
}

export function pickRandom(palette: string[], rng: () => number): string {
  if (palette.length === 0) return '#000000';
  return palette[Math.floor(rng() * palette.length)];
}

function parseHex(hex: string): [number, number, number] {
  const h = hex.replace('#', '');
  const full = h.length === 3 ? h.split('').map((c) => c + c).join('') : h;
  return [
    parseInt(full.slice(0, 2), 16),
    parseInt(full.slice(2, 4), 16),
    parseInt(full.slice(4, 6), 16),
  ];
}

function toHex(r: number, g: number, b: number): string {
  const h = (n: number) => Math.round(Math.max(0, Math.min(255, n))).toString(16).padStart(2, '0');
  return `#${h(r)}${h(g)}${h(b)}`;
}

export function mixHex(a: string, b: string, t: number): string {
  const [r1, g1, b1] = parseHex(a);
  const [r2, g2, b2] = parseHex(b);
  return toHex(r1 + (r2 - r1) * t, g1 + (g2 - g1) * t, b1 + (b2 - b1) * t);
}
